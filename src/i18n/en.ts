/**
 * DOR101 interface string table (English source of truth).
 *
 * Scope rule, enforced by the build:
 *   This file contains *interface* text only. Labels, buttons, statuses,
 *   messages, control names. Long form community content (organisation
 *   descriptions, FAQ answers, neighborhood profiles) lives in
 *   `src/i18n/content.ts` as Localized records, because that content changes
 *   on its own schedule and is verified with partner organisations.
 *
 * Every locale is typed `Record<TranslationKey, string>`. A missing key is a
 * TypeScript error, and `i18n-coverage.test.ts` additionally checks key
 * parity, placeholder parity and the translation coverage figure shown in
 * Settings. Silent fallback to English is therefore impossible.
 *
 * Copy conventions (they are also the tells AI-generated UI text usually misses):
 *   - sentence case, no terminal punctuation on labels
 *   - no em dashes, no middot separators, no "seamless"/"leverage"/"curated"
 *   - numbers, dates and currency always go through Intl in `src/lib/format.ts`
 */

