/** Placeholder names used inside a string, e.g. `{count}` in "Saved {count} places". */
export function placeholdersOf(value: string): string[] {
  return (value.match(/\{[a-zA-Z0-9_.]+(?:,[a-zA-Z0-9_.=]+)*\}/g) ?? []).map((raw) =>
    raw.slice(1, raw.indexOf(raw.includes(',') ? ',' : '}')).trim()
  );
}
