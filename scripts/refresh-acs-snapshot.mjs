#!/usr/bin/env node
/**
 * Regenerates the verified ACS capture in `src/lib/census.ts`.
 *
 * The capture is the last-resort source for the market page: it is shown only
 * when every live Census endpoint fails, and it is labelled as a capture. That
 * only stays true if someone refreshes it when the Bureau publishes a new
 * 5-year release, so this script reads the same tables the live reader reads
 * and rewrites the block between the `SNAPSHOT:BEGIN` / `SNAPSHOT:END` markers.
 *
 *   node scripts/refresh-acs-snapshot.mjs [--vintage 2024] [--dry-run]
 *
 * It talks to data.census.gov's keyless table service — the same endpoint the
 * site uses — or to api.census.gov when CENSUS_API_KEY is set.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const TARGET = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'lib', 'census.ts');
const GEO_UCGID = '050XX00US25025';
const TABLES = ['B19013', 'B25058', 'B25064', 'B25088', 'B25077', 'B25003', 'B25070', 'B25071'];

const args = process.argv.slice(2);
const vintage = args.includes('--vintage') ? args[args.indexOf('--vintage') + 1] : '2024';
const dryRun = args.includes('--dry-run');
/** Overridable so the script can be exercised against a stub in CI. */
const base = (args.includes('--base') ? args[args.indexOf('--base') + 1] : 'https://data.census.gov').replace(/\/$/, '');

/** ACS sentinels for "no estimate"; a snapshot must never carry one. */
function clean(raw) {
  if (raw === null || raw === undefined || raw === '') return null;
  const n = Number(raw);
  if (!Number.isFinite(n)) return null;
  if (n <= -1111111111 || n >= 2222222222) return null;
  if ([-666666666, -888888888, -999999999, -222222222].includes(n)) return null;
  return n;
}

async function readTable(table) {
  const url = `${base}/api/access/data/table?id=ACSDT5Y${vintage}.${table}&g=${GEO_UCGID}`;
  const res = await fetch(url, { headers: { accept: 'application/json' } });
  if (!res.ok) throw new Error(`${table}: HTTP ${res.status}`);
  const json = await res.json();
  const data = json?.response?.data;
  if (!Array.isArray(data) || data.length < 2) throw new Error(`${table}: unexpected shape`);
  const [header, row] = data;
  const out = {};
  header.forEach((column, index) => {
    const match = /^(B\d+_\d+)(E|M)$/.exec(column);
    if (!match) return;
    const id = `${match[1]}E`;
    const value = clean(row[index]);
    if (value === null) return;
    out[id] ??= { value: null, moe: null };
    if (match[2] === 'M') out[id].moe = value;
    else out[id].value = value;
  });
  return out;
}

const found = {};
for (const table of TABLES) {
  const part = await readTable(table);
  Object.assign(found, part);
  console.log(`  ${table}: ${Object.keys(part).length} variables`);
}

const missing = TABLES.flatMap((t) => Object.keys(found).filter((k) => k.startsWith(t)).length === 0 ? [t] : []);
if (missing.length) {
  console.error(`Refusing to write a partial capture; no data for: ${missing.join(', ')}`);
  process.exit(1);
}

// The rent-burden bins must add up to the table total, or the shares the page
// computes from them are wrong. Checked here because the snapshot has no
// live read behind it to disagree with.
const b = (n) => found[`B25070_${String(n).padStart(3, '0')}E`]?.value;
const binsSum = [2, 3, 4, 5, 6, 7, 8, 9, 10].reduce((a, n) => a + (b(n) ?? 0), 0) + (b(11) ?? 0);
if (b(1) !== binsSum) {
  console.error(`B25070 bins sum to ${binsSum} but the table total is ${b(1)}; not writing.`);
  process.exit(1);
}

const entries = Object.entries(found)
  .sort(([x], [y]) => x.localeCompare(y))
  .map(([id, { value, moe }]) => `    ${id}: [${String(value).replace(/\B(?=(\d{3})+(?!\d))/g, '_')}, ${moe === null ? 'null' : String(moe).replace(/\B(?=(\d{3})+(?!\d))/g, '_')}],`)
  .join('\n');

const block = `/* SNAPSHOT:BEGIN — regenerated by scripts/refresh-acs-snapshot.mjs */
export const ACS_SNAPSHOT = {
  vintage: '${vintage}',
  geography: 'Suffolk County, Massachusetts',
  capturedAt: '${new Date().toISOString()}',
  /** [estimate, margin of error] per variable. */
  estimates: {
${entries}
  } as Record<string, [number, number | null]>,
} as const;
/* SNAPSHOT:END */`;

const source = readFileSync(TARGET, 'utf8');
const pattern = /\/\* SNAPSHOT:BEGIN[\s\S]*?\/\* SNAPSHOT:END \*\//;
if (!pattern.test(source)) {
  console.error(`Could not find the SNAPSHOT markers in ${TARGET}.`);
  process.exit(1);
}

if (dryRun) {
  console.log(block);
} else {
  writeFileSync(TARGET, source.replace(pattern, block), 'utf8');
  console.log(`\nWrote ${Object.keys(found).length} ACS ${vintage} estimates to src/lib/census.ts`);
}
